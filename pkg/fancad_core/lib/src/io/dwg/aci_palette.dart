/// The first ACI index whose RGB equals [rgb], or 256 when no entry matches.
///
/// Used when a layer stores a true colour but no usable ACI index: the reference decoder
/// searches this table for an exact match and falls back to 256. An exact
/// match matters because the file may have been saved by a reader that wrote
/// the palette value as a true colour.
int aciIndexForRgb(int rgb) {
  final colour = rgb & 0xffffff;
  for (var i = 0; i < aciRgbPalette.length; i++) {
    if (aciRgbPalette[i] == colour) return i;
  }
  return 256;
}

/// The closest ACI index to [rgb], ignoring the ByBlock and ByLayer entries.
///
/// Used when a writer has to store a true colour in a format that only carries
/// an ACI value, such as R2000.
int nearestAciIndexForRgb(int rgb) {
  final r = (rgb >> 16) & 0xff;
  final g = (rgb >> 8) & 0xff;
  final b = rgb & 0xff;
  var best = 7;
  var bestDistance = 1 << 30;
  for (var i = 1; i < 256; i++) {
    final colour = aciRgbPalette[i];
    final dr = ((colour >> 16) & 0xff) - r;
    final dg = ((colour >> 8) & 0xff) - g;
    final db = (colour & 0xff) - b;
    final distance = dr * dr + dg * dg + db * db;
    if (distance < bestDistance) {
      bestDistance = distance;
      best = i;
      if (distance == 0) break;
    }
  }
  return best;
}
